"""Chart helper: real-data, code-rendered chart images (16:9 PNG).

Used to render data tables (e.g. VDOT → pace) as image frames for the video
pipeline. Data is rendered programmatically with matplotlib, not generated by AI
[Crystal ref: D-009].
"""

from __future__ import annotations

import re

from typing import Sequence, Tuple

import matplotlib

matplotlib.use("Agg")  # headless rendering, no display required

import matplotlib.pyplot as plt  # noqa: E402


# Chinese fonts available on macOS: try common ones; matplotlib falls back gracefully.
_CN_FONTS = ["PingFang SC", "STHeiti", "Heiti TC", "Heiti SC", "SimHei", "WenQuanYi Micro Hei"]

# Unicode superscript characters → their plain counterparts. The CN fonts above
# lack the superscript glyphs (e.g. SUPERSCRIPT MINUS / U+207B), so a unit like
# "J·kg⁻¹·m⁻¹" renders the superscripts as tofu boxes (□). We rewrite each run of
# superscripts into matplotlib mathtext ($^{-1}$), which renders proper small
# raised digits font-independently while the CJK parts stay in the CN font.
_SUPERSCRIPT_MAP = {
    "⁰": "0", "¹": "1", "²": "2", "³": "3", "⁴": "4", "⁵": "5",
    "⁶": "6", "⁷": "7", "⁸": "8", "⁹": "9", "⁻": "-", "⁺": "+", "⁼": "=",
}
_SUPERSCRIPT_RE = re.compile("[" + "".join(_SUPERSCRIPT_MAP) + "]+")


def _superscripts_to_mathtext(text: str) -> str:
    """Rewrite Unicode superscript runs in ``text`` into mathtext ``$^{...}$``.

    "能耗 (J·kg⁻¹·m⁻¹)" → "能耗 (J·kg$^{-1}$·m$^{-1}$)". Leaves text unchanged when
    it has no superscripts, or already contains a literal ``$`` (which would make
    mathtext parsing ambiguous — we don't second-guess an author-supplied formula).
    """
    if "$" in text or not _SUPERSCRIPT_RE.search(text):
        return text
    return _SUPERSCRIPT_RE.sub(
        lambda m: "$^{" + "".join(_SUPERSCRIPT_MAP[c] for c in m.group()) + "}$",
        text,
    )


def _setup_rcparams() -> None:
    """Configure matplotlib for clean 16:9 chart with Chinese support."""
    matplotlib.rcParams["font.sans-serif"] = list(_CN_FONTS)
    matplotlib.rcParams["font.family"] = "sans-serif"
    matplotlib.rcParams["axes.unicode_minus"] = False
    # mathtext (used for superscript units, see _superscripts_to_mathtext) renders
    # in the regular sans font rather than the default italic serif, so the raised
    # digits match the axis label weight.
    matplotlib.rcParams["mathtext.default"] = "regular"
    # 16:9 at 1920x1080 base; scale font sizes up accordingly.
    matplotlib.rcParams["font.size"] = 28
    matplotlib.rcParams["axes.titlesize"] = 36
    matplotlib.rcParams["axes.labelsize"] = 28


# Bottom safe-area: line/bar charts reserve this fraction of the figure height at
# the bottom so the burned-in subtitle (bottom-center ASS, MarginV=78, up to 2
# lines → top ~0.16 from bottom) does not collide with the x-axis label/ticks
# (E2E acceptance #6-subtitle). Empirically 0.20 still overlapped the x-axis LABEL
# with a 2-line subtitle; 0.28 pushes the axis label above the subtitle band.
CHART_BOTTOM_SAFE = 0.28
# Top safe-area: reserve the top band for the chart title so content sits in a
# centered middle band (title above, subtitle below). R2: charts are centered
# WITHIN [CHART_BOTTOM_SAFE, 1-CHART_TOP_SAFE], not pinned to the top.
CHART_TOP_SAFE = 0.12

# Table is centered within the bottom-safe region via an explicit bbox (below);
# _TABLE_LOC documents the intent ("center") and is asserted by the tests. An
# explicit bbox (not loc) is what actually enforces fit+centering for any row count.
_TABLE_LOC = "center"


def render_pace_table(
    title: str,
    rows: Sequence[Tuple[str, str]],
    out_path: str,
    size: Tuple[int, int] = (1920, 1080),
) -> str:
    """Render a 16:9 chart PNG containing a pace/data table.

    Args:
        title: Chart title (Chinese supported via PingFang SC).
        rows: Sequence of (label, value) pairs to display in the table body.
        out_path: Destination .png file path. Parent directory must exist.
        size: (width, height) in pixels. Defaults to 1920x1080 (16:9 1080p).

    Returns:
        The out_path on success.

    Notes:
        Data is rendered programmatically from the supplied rows. No AI / no
        random generation. Table is centered, with clear headers and rows.
    """
    _setup_rcparams()

    width_in = size[0] / 100.0
    height_in = size[1] / 100.0

    fig, ax = plt.subplots(figsize=(width_in, height_in), dpi=100)
    ax.axis("off")  # hide the Cartesian frame; we only want the table

    fig.patch.set_facecolor("#FAFAFA")
    ax.set_facecolor("#FAFAFA")

    # Build a table with a header row + N data rows.
    table_data = [["配速区间", "对应时间"]] + [list(r) for r in rows]

    # Explicit bbox centers the table WITHIN the bottom-safe region [CHART_BOTTOM_SAFE,
    # 1-CHART_TOP_SAFE] and makes it fill that band evenly for ANY row count — the
    # bottom band stays clear for the burned subtitle, the top band holds the title,
    # and the table reads as centered (R2). bbox overrides loc; it is in axes coords
    # (axes = full figure here), so [x0, y0, w, h] maps straight to the frame.
    _tbl_h = 1.0 - CHART_TOP_SAFE - CHART_BOTTOM_SAFE
    tbl = ax.table(
        cellText=table_data,
        colWidths=[0.45, 0.45],
        cellLoc="center",
        bbox=[0.06, CHART_BOTTOM_SAFE, 0.88, _tbl_h],
    )
    tbl.auto_set_font_size(False)
    tbl.set_fontsize(28)

    # Style the header row differently from the body.
    for col in range(2):
        cell = tbl[(0, col)]
        cell.set_facecolor("#2C3E50")
        cell.set_text_props(color="white", weight="bold", fontsize=32)
        cell.set_edgecolor("#1A252F")

    # Alternate row striping for readability.
    for row_idx in range(1, len(table_data)):
        face = "#FFFFFF" if row_idx % 2 == 1 else "#ECF0F1"
        for col in range(2):
            cell = tbl[(row_idx, col)]
            cell.set_facecolor(face)
            cell.set_edgecolor("#BDC3C7")
            cell.set_text_props(fontsize=28)

    # Title above the table.
    ax.set_title(title, fontsize=40, weight="bold", pad=24, color="#2C3E50")

    plt.tight_layout(pad=0.5)
    # Fixed-size output: no bbox_inches="tight" (that would crop to content and
    # change the aspect ratio from the requested 16:9). Save at the figure's
    # full canvas size so the resulting PNG is exactly 1920x1080 at dpi=100.
    fig.savefig(out_path, dpi=100, facecolor=fig.get_facecolor())
    plt.close(fig)

    return out_path


def build_zone_boundary_chart(zone_data):
    """Build a (title, rows) intensity-zone boundary chart from the authoritative
    ``zone_boundary_data.json`` (no AI, no random — faithfulness-safe).

    Returns ``(title, rows)`` where rows is a list of ``(code, "vo2max% / hrmax%")``
    tuples, or ``None`` if the data is missing or empty (caller decides how to handle).
    """
    if not zone_data:
        return None
    zones = zone_data.get("zones") or []
    if not zones:
        return None
    title = "七区强度边界（%VO2max / %HRmax）"
    rows = [(z["code"], f'{z["vo2max"]} / {z["hrmax"]}') for z in zones]
    return title, rows


def build_line_chart(
    title: str,
    x_label: str,
    y_label: str,
    points: Sequence[Tuple[float, float]],
    out_path: str,
    size: Tuple[int, int] = (1920, 1080),
) -> str:
    """Render a 16:9 line/curve chart PNG from inline data points.

    Args:
        title: Chart title (Chinese supported via PingFang SC).
        x_label: X-axis label.
        y_label: Y-axis label.
        points: Sequence of (x, y) numeric pairs defining the line.
        out_path: Destination .png file path. Parent directory must exist.
        size: (width, height) in pixels. Defaults to 1920x1080 (16:9 1080p).

    Returns:
        The out_path on success.

    Notes:
        Data is rendered programmatically from the supplied points. No AI / no
        random generation. Line chart uses the standard matplotlib line style.
    """
    _setup_rcparams()

    width_in = size[0] / 100.0
    height_in = size[1] / 100.0

    fig, ax = plt.subplots(figsize=(width_in, height_in), dpi=100)
    fig.patch.set_facecolor("#FAFAFA")
    ax.set_facecolor("#F5F6FA")

    xs = [p[0] for p in points]
    ys = [p[1] for p in points]

    ax.plot(xs, ys, color="#2C7BE5", linewidth=3, marker="o", markersize=8,
            markerfacecolor="#E74C3C", markeredgecolor="#C0392B", zorder=3)

    # Superscript units (J·kg⁻¹·m⁻¹) → mathtext so the CN fonts don't tofu them.
    ax.set_xlabel(_superscripts_to_mathtext(x_label), fontsize=28, color="#2C3E50")
    ax.set_ylabel(_superscripts_to_mathtext(y_label), fontsize=28, color="#2C3E50")
    ax.set_title(_superscripts_to_mathtext(title), fontsize=40, weight="bold",
                 pad=24, color="#2C3E50")

    ax.tick_params(labelsize=24, colors="#555555")
    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)
    ax.spines["left"].set_color("#BDC3C7")
    ax.spines["bottom"].set_color("#BDC3C7")
    ax.grid(axis="y", color="#ECF0F1", linewidth=1.5, zorder=0)

    plt.tight_layout(pad=1.0)
    # Reserve bottom (subtitle) + top (title) bands → plot sits in the centered
    # middle band, x-axis label clears the burned subtitle.
    fig.subplots_adjust(bottom=CHART_BOTTOM_SAFE, top=1.0 - CHART_TOP_SAFE)
    fig.savefig(out_path, dpi=100, facecolor=fig.get_facecolor())
    plt.close(fig)

    return out_path


def build_bar_chart(
    title: str,
    x_label: str,
    y_label: str,
    categories: Sequence[str],
    values: Sequence[float],
    out_path: str,
    size: Tuple[int, int] = (1920, 1080),
    return_ax: bool = False,
):
    """Render a 16:9 **0-baseline** bar chart for discrete/equivalence comparison.

    Unlike a 2-point line (which autoscales its y-axis and exaggerates a tiny
    difference into a steep slope), a 0-baseline bar chart shows two near-equal
    values as two near-equal bars — honest for "无显著差异" data (E2E #1 fix).

    Args:
        title/x_label/y_label: labels (Chinese OK).
        categories: bar category labels (e.g. ["10%/周", "50%/周"]).
        values: bar heights, 1:1 with categories. Must be real, sourced numbers.
        out_path: destination .png.
        size: (w, h) px, default 1920x1080.
        return_ax: when True, return the Axes (for tests) instead of the path.

    Returns:
        out_path (str), or the Axes when return_ax=True.
    """
    _setup_rcparams()
    width_in = size[0] / 100.0
    height_in = size[1] / 100.0

    fig, ax = plt.subplots(figsize=(width_in, height_in), dpi=100)
    fig.patch.set_facecolor("#FAFAFA")
    ax.set_facecolor("#F5F6FA")

    xs = list(range(len(categories)))
    bars = ax.bar(xs, list(values), color="#2C7BE5", width=0.5, zorder=3)
    ax.set_xticks(xs)
    ax.set_xticklabels([_superscripts_to_mathtext(str(c)) for c in categories])
    ax.set_ylim(bottom=0)  # 0 baseline — the honesty guarantee

    # Value labels above each bar.
    for rect, val in zip(bars, values):
        ax.annotate(f"{val}", xy=(rect.get_x() + rect.get_width() / 2, val),
                    xytext=(0, 6), textcoords="offset points",
                    ha="center", va="bottom", fontsize=24, color="#2C3E50")

    ax.set_xlabel(_superscripts_to_mathtext(x_label), fontsize=28, color="#2C3E50")
    ax.set_ylabel(_superscripts_to_mathtext(y_label), fontsize=28, color="#2C3E50")
    ax.set_title(_superscripts_to_mathtext(title), fontsize=40, weight="bold",
                 pad=24, color="#2C3E50")
    ax.tick_params(labelsize=24, colors="#555555")
    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)
    ax.spines["left"].set_color("#BDC3C7")
    ax.spines["bottom"].set_color("#BDC3C7")
    ax.grid(axis="y", color="#ECF0F1", linewidth=1.5, zorder=0)

    plt.tight_layout(pad=1.0)
    # Bottom (subtitle) + top (title) safe bands → bars sit in the centered band.
    fig.subplots_adjust(bottom=CHART_BOTTOM_SAFE, top=1.0 - CHART_TOP_SAFE)
    fig.savefig(out_path, dpi=100, facecolor=fig.get_facecolor())
    if return_ax:
        return ax
    plt.close(fig)
    return out_path


def build_pace_chart_from_vdot(vdot_data, target_vdot: int = 50):
    """Build a (title, rows) pace-zone chart for a representative VDOT, pulled
    straight from the authoritative ``vdot_pace_data.json`` (no AI, no random —
    faithfulness-safe). Picks the data row nearest ``target_vdot`` and lists its
    five training-pace zones (E / M / T / I / R) with real paces.

    Returns ``(title, rows)`` where rows is a list of (label, value) tuples, or
    ``None`` if no usable data (caller decides how to handle a chart beat with no
    authoritative table).
    """
    from lib.extract import _min_to_mmss, _secs_to_mmss

    data = (vdot_data or {}).get("data", [])
    if not data:
        return None
    entry = min(data, key=lambda e: abs((e.get("vdot") or 0) - target_vdot))
    vdot = entry.get("vdot")
    p = entry.get("paces", {})
    rows = []
    if p.get("easyMin") is not None and p.get("easyMax") is not None:
        rows.append(("轻松跑 E", f"{_min_to_mmss(p['easyMin'])}–{_min_to_mmss(p['easyMax'])}/km"))
    if p.get("marathon") is not None:
        rows.append(("马拉松配速 M", f"{_min_to_mmss(p['marathon'])}/km"))
    if p.get("threshold") is not None:
        rows.append(("乳酸阈 T", f"{_min_to_mmss(p['threshold'])}/km"))
    if p.get("interval") is not None:
        rows.append(("间歇 I", f"{_min_to_mmss(p['interval'])}/km"))
    if p.get("repetition400m") is not None:
        rows.append(("重复 R", f"{_secs_to_mmss(p['repetition400m'])}/400m"))
    if not rows:
        return None
    return f"VDOT {vdot} 训练配速参考", rows
